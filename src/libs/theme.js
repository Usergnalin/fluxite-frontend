export const THEME_OPTIONS = Object.entries(THEME_PRESETS).map(([id, theme]) => ({
    id,
    ...theme,
}))

export function getStoredTheme() {
    if (typeof window === 'undefined') return 'github'
    return window.localStorage.getItem(THEME_STORAGE_KEY) || 'github'
}

export function applyTheme(themeId) {
    const theme = THEME_PRESETS[themeId] || THEME_PRESETS.github
    if (typeof document === 'undefined') return theme

    const root = document.documentElement
    root.style.setProperty('--color-bg-primary', theme.bgPrimary)
    root.style.setProperty('--color-bg-secondary', theme.bgSecondary)
    root.style.setProperty('--color-bg-tertiary', theme.bgTertiary)
    root.style.setProperty('--color-bg-card', theme.bgCard)
    root.style.setProperty('--color-bg-card-hover', theme.bgCardHover)
    root.style.setProperty('--color-bg-surface', theme.bgSurface)
    root.style.setProperty('--color-bg-modal', theme.bgModal)
    root.style.setProperty('--color-bg-input', theme.bgInput)
    root.style.setProperty('--color-bg-create', theme.bgCreate)
    root.style.setProperty('--color-bg-create-hover', theme.bgCreateHover)
    root.style.setProperty('--color-border-primary', theme.borderPrimary)
    root.style.setProperty('--color-border-secondary', theme.borderSecondary)
    root.style.setProperty('--color-text-primary', theme.textPrimary)
    root.style.setProperty('--color-text-secondary', theme.textSecondary)
    root.style.setProperty('--color-text-muted', theme.textMuted)
    root.style.setProperty('--color-text-heading', theme.textHeading)
    root.style.setProperty('--color-accent-primary', theme.accent)
    root.style.setProperty('--color-accent-hover', theme.accentHover)
    root.style.setProperty('--color-accent-light', theme.accentLight)
    root.style.setProperty('--color-status-online', theme.statusOnline)
    root.style.setProperty('--color-status-starting', theme.statusStarting)
    root.style.setProperty('--color-status-stopping', theme.statusStopping)
    root.style.setProperty('--color-status-offline', theme.statusOffline)
    root.style.setProperty('--color-error', theme.error)
    root.style.setProperty('--color-error-light', theme.errorLight)
    root.style.setProperty('--color-success', theme.success)
    root.style.setProperty('--color-warning', theme.warning)
    root.style.setProperty('--app-body-glow', theme.glow)
    root.style.setProperty('--app-body-start', theme.bodyStart)
    root.style.setProperty('--app-body-end', theme.bodyEnd)
    root.style.setProperty('--app-selection-bg', theme.selection)
    root.dataset.theme = themeId
    return theme
}
